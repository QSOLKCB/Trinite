"""Source-bound historical admission and exact prospective row correspondence.

Only ``materialize_inputs`` constructs an admitted input object. It executes the
retained, independently byte-pinned audit in its original isolated worker and
runs current admission in a fresh source-only snapshot. No caller-supplied pass,
row list, scheduler, executable, or replacement expected digest is accepted.
This module has no numerical dependencies and performs no model calls.
"""
from dataclasses import dataclass
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import types

from ..contracts import ContractError, identity, integer, json_bytes, parse_json

HISTORICAL_COMMIT = "93522bf8f18fe38970ceafdd2ace792f8922c382"
HISTORICAL_TREE = "c8cc28e560729722539a2a6ee47408f50a7a802e"
HISTORICAL_DATASET = "sha256:120b95ac68825b50b92dc0210d1f142a30980bfe5acedcfafe6d8f3cdadf83c4"
HISTORICAL_MANIFEST = "sha256:315168dd6be4909cead81a45a4c3b5b1abb125cc69f3ca773b5145f18b0ac412"
AUDIT_IDENTITY = "sha256:00894610c3ebb2d61590a6320aeedd029fdfaae7b66344c137632d097a1dfa53"
COMPARISON_IDENTITY = "sha256:7e0160ac9ca5c6241dd8001bbc8775c6dd1c51266755533705debd819d9a087b"
AUDIT_RELATIVE_PATH = "docs/evidence/procedural-qec-control-order/audit.py"
COMPARISON_RELATIVE_PATH = "docs/evidence/procedural-qec-control-order/comparison.json"
IGNORED_ROW_FIELDS = frozenset(("generator_revision", "example_identity"))
MAX_ROUNDS = 4096
ROWS = 3876
_INPUT_AUTHORITY = object()

# A fixed controller-owned entry point. The only path is the fresh verified
# snapshot constructed here, never an arbitrary executable supplied by a user.
_CURRENT_WORKER = """import pathlib, sys
sys.path.insert(0, str(pathlib.Path(sys.argv[1]) / 'src'))
from trinite.contracts import json_bytes, parse_json
from trinite.procedural_qec import data
raw, manifest = data.dataset()
data.audit_bytes(raw, manifest)
if any(name.split('.')[0] in ('torch', 'numpy') for name in sys.modules):
    raise RuntimeError('unexpected numerical dependency in input admission')
sys.stdout.buffer.write(json_bytes({'dataset': parse_json(raw, canonical=True),
                                   'manifest': parse_json(manifest, canonical=True)}))
"""


def _require(condition, message):
    if not condition:
        raise ContractError(message)


def _safe_path(path):
    path = Path(path).absolute()
    _require(not any(p.is_symlink() for p in (path, *path.parents)),
             "auxiliary inputs cannot traverse symlinks")
    return path


def _read(path, limit):
    path = _safe_path(path)
    _require(path.is_file(), "missing auxiliary input source: " + path.name)
    with path.open("rb") as stream:
        raw = stream.read(limit + 1)
    _require(len(raw) <= limit, "auxiliary input source exceeds byte budget")
    return raw


def _repository(repository):
    root = _safe_path(repository if repository is not None else Path(__file__).resolve().parents[3])
    _require(root.is_dir(), "auxiliary repository directory required")
    return root


def _load_audit(repository):
    """Load verified bytes, never import a mutable pathname or cached bytecode."""
    path = repository / AUDIT_RELATIVE_PATH
    raw = _read(path, 64 * 1024)
    _require(identity(raw) == AUDIT_IDENTITY, "independently pinned historical audit changed")
    module = types.ModuleType("trinite_auxiliary_historical_audit")
    module.__file__ = str(path)
    exec(compile(raw, str(path), "exec"), module.__dict__)
    try:
        receipt = module.read_receipt(repository / COMPARISON_RELATIVE_PATH)
    except ValueError as error:
        raise ContractError(str(error)) from error
    _require(identity(receipt) == COMPARISON_IDENTITY, "original comparison commitment changed")
    return module, raw, receipt


def _source_snapshot():
    """Complete bounded current source closure, excluding generated byproducts.

    The isolated current worker runs only these captured bytes. Unknown files
    and symlinks fail rather than allowing an unbound import extension/shadow.
    The enclosing producer additionally binds its launcher and protocol assets.
    """
    root = _safe_path(Path(__file__).absolute().parents[3])
    src = _safe_path(root / "src")
    _require(src.is_dir(), "source checkout required for auxiliary materialization")
    files, entries, total = {}, 0, 0
    allowed = {".py", ".json", ".txt", ".lock", ".cff"}

    def scan_error(error):
        raise ContractError("cannot enumerate auxiliary input source") from error

    for directory, dirs, names in os.walk(src, followlinks=False, onerror=scan_error):
        entries += len(dirs) + len(names)
        _require(entries <= 10000, "auxiliary source traversal bound exceeded")
        base = Path(directory)
        for name in dirs + names:
            _safe_path(base / name)
        dirs[:] = sorted(name for name in dirs if name != "__pycache__"
                         and not name.endswith((".egg-info", ".dist-info")))
        for name in sorted(names):
            path = base / name
            _require(path.suffix in allowed, "unsupported auxiliary source member: " + name)
            raw = _read(path, 1024 * 1024)
            total += len(raw)
            _require(total <= 64 * 1024 * 1024 and len(files) < 512,
                     "auxiliary source inventory bound exceeded")
            files[path.relative_to(root).as_posix()] = raw
    _require("src/trinite/procedural_qec/data.py" in files,
             "missing prospective generator source")
    return files


def _source_receipt(files):
    return {name: identity(raw) for name, raw in sorted(files.items())}


def _run_current(files):
    with tempfile.TemporaryDirectory(prefix="trinite-auxiliary-current-") as directory:
        root = Path(directory)
        for name, raw in files.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
        process = subprocess.run(
            [sys.executable, "-I", "-S", "-B", "-c", _CURRENT_WORKER, str(root)],
            capture_output=True, check=False, timeout=300)
    _require(process.returncode == 0, "prospective isolated admission failed: " +
             process.stderr.decode(errors="replace")[-2000:])
    _require(len(process.stdout) <= 16 * 1024 * 1024, "prospective admission output exceeds bound")
    payload = parse_json(process.stdout, canonical=True)
    _require(type(payload) is dict and set(payload) == {"dataset", "manifest"},
             "prospective admission payload schema mismatch")
    return json_bytes(payload["dataset"]), json_bytes(payload["manifest"])


def normalized(row):
    """Remove exactly the two permitted TOP-LEVEL identity fields."""
    _require(type(row) is dict, "row must be an object")
    return {key: value for key, value in row.items() if key not in IGNORED_ROW_FIELDS}


def _bijection(audit, historical, prospective):
    try:
        old = audit.row_map(historical)
        new = audit.row_map(prospective)
    except (TypeError, KeyError, ValueError) as error:
        raise ContractError("invalid row bijection: " + str(error)) from error
    _require(old.keys() == new.keys(), "missing or extra prospective mathematical rows")
    mapping = []
    current_indices = {row["example_identity"]: index
                       for index, row in enumerate(prospective["examples"])}
    for row in historical["examples"]:
        other = new[row["prompt"], row["answer"]]
        raw = json_bytes(normalized(row))
        _require(raw == json_bytes(normalized(other)),
                 "row differs beyond generator_revision/example_identity")
        mapping.append({"historical_identity": row["example_identity"],
                        "prospective_identity": other["example_identity"],
                        "normalized_identity": identity(raw),
                        "prospective_index": current_indices[other["example_identity"]]})
    _require(len(mapping) == ROWS and len({m["prospective_index"] for m in mapping}) == ROWS,
             "row correspondence is not a complete bijection")
    return mapping


def _validate_historical(audit, payload, comparison):
    try:
        audit.validate_payload(payload, "historical")
    except (TypeError, KeyError, ValueError) as error:
        raise ContractError("invalid original audit payload: " + str(error)) from error
    old = payload["dataset"]["examples"]
    for index, (seed, arm) in enumerate(audit.CELLS):
        rows = [old[i] for i in payload["schedules"]["v2"][index]]
        record = comparison["cells"][index]
        _require(record["seed"] == seed and record["arm"] == arm
                 and identity(audit.canonical([(r["prompt"], r["answer"]) for r in rows]))
                 == record["historical_sequence_identity"],
                 "original historical sequence commitment mismatch")


@dataclass(frozen=True, slots=True, init=False)
class MaterializedInputs:
    """Immutable exact bytes with fresh-copy accessors, not a saved pass flag."""
    historical_source: Path
    repository: Path
    dataset_raw: bytes
    manifest_raw: bytes
    historical_dataset_raw: bytes
    historical_manifest_raw: bytes
    historical_payload_raw: bytes
    receipt_raw: bytes
    _authority: object
    _binding_raw: bytes

    def __init__(self, *args, **kwargs):
        raise ContractError("use materialize_inputs for actual source-bound admission")

    @property
    def items(self):
        return parse_json(self.dataset_raw, canonical=True)["examples"]

    @property
    def historical_items(self):
        return parse_json(self.historical_dataset_raw, canonical=True)["examples"]

    @property
    def receipt(self):
        return parse_json(self.receipt_raw, canonical=True)

    def primary_indices(self, seed):
        integer(seed, "auxiliary seed", 0, 1)
        mapping = self.receipt["mapping"]
        schedule = parse_json(self.historical_payload_raw, canonical=True)["schedules"]["v2"][seed * 2]
        return tuple(mapping[index]["prospective_index"] for index in schedule)

    @property
    def content_identity(self):
        return identity(self.receipt_raw)


def _bytes_binding(inputs):
    return json_bytes({name: identity(getattr(inputs, name)) for name in
        ("dataset_raw", "manifest_raw", "historical_dataset_raw", "historical_manifest_raw",
         "historical_payload_raw", "receipt_raw")})


def materialize_inputs(historical_source, *, repository=None):
    """Reconstruct/admit the actual historical and prospective producer inputs."""
    repository = _repository(repository)
    historical_source = _safe_path(historical_source).resolve(strict=True)
    audit, audit_raw, comparison_raw = _load_audit(repository)
    try:
        audit.verify_source(historical_source, "historical")
        _require(audit.git(historical_source, "rev-parse", "HEAD^{tree}").decode().strip()
                 == HISTORICAL_TREE, "historical Git tree mismatch")
        snapshot = _source_snapshot()
        # Exact verified audit bytes in a private directory close the pathname
        # substitution window between source validation and worker dispatch.
        with tempfile.TemporaryDirectory(prefix="trinite-auxiliary-audit-") as directory:
            pinned = Path(directory) / "audit.py"
            pinned.write_bytes(audit_raw)
            audit.__file__ = str(pinned)
            payload = audit.run_worker(historical_source, "historical")
            _require(pinned.read_bytes() == audit_raw, "isolated historical audit changed")
        _validate_historical(audit, payload, parse_json(comparison_raw, canonical=True))
        raw, manifest = _run_current(snapshot)
        _require(_source_snapshot() == snapshot, "prospective source changed during admission")
        audit.verify_source(historical_source, "historical")
        _, final_audit, final_comparison = _load_audit(repository)
        _require((final_audit, final_comparison) == (audit_raw, comparison_raw),
                 "historical evidence changed during admission")
    except (OSError, subprocess.SubprocessError, ValueError) as error:
        if isinstance(error, ContractError):
            raise
        raise ContractError("source-bound materialization failed: " + str(error)) from error
    prospective = parse_json(raw, canonical=True)
    mapping = _bijection(audit, payload["dataset"], prospective)
    historical_raw = json_bytes(payload["dataset"])
    historical_manifest = json_bytes(payload["manifest"])
    payload_raw = json_bytes(payload)
    receipt = {"schema": "trinite.procedural-qec-auxiliary-inputs.v1",
        "historical_producer_commit": HISTORICAL_COMMIT,
        "historical_git_tree": HISTORICAL_TREE,
        "historical_dataset_identity": identity(historical_raw),
        "historical_manifest_identity": identity(historical_manifest),
        "historical_payload_identity": identity(payload_raw),
        "audit_script_identity": AUDIT_IDENTITY,
        "original_comparison_identity": COMPARISON_IDENTITY,
        "prospective_dataset_identity": identity(raw),
        "prospective_manifest_identity": identity(manifest),
        "prospective_source": _source_receipt(snapshot),
        "ignored_top_level_row_fields": sorted(IGNORED_ROW_FIELDS),
        "mapping": mapping,
        "historical_primary_sequence_identities": {
            str(seed): parse_json(comparison_raw, canonical=True)["cells"][seed * 2]
                ["historical_sequence_identity"] for seed in (0, 1)}}
    result = object.__new__(MaterializedInputs)
    for name, value in {"historical_source": historical_source, "repository": repository,
            "dataset_raw": raw, "manifest_raw": manifest,
            "historical_dataset_raw": historical_raw,
            "historical_manifest_raw": historical_manifest,
            "historical_payload_raw": payload_raw, "receipt_raw": json_bytes(receipt),
            "_authority": _INPUT_AUTHORITY}.items():
        object.__setattr__(result, name, value)
    object.__setattr__(result, "_binding_raw", _bytes_binding(result))
    return result


def revalidate(inputs):
    """Recheck bytes and both live sources, without caching a verifier verdict.

    Historical admission executed at construction; immutable payload bytes are
    rechecked against fixed historical dataset/manifest/sequence commitments.
    Source changes require a new materialization and a separately bound request.
    """
    _require(type(inputs) is MaterializedInputs
             and inputs._authority is _INPUT_AUTHORITY,
             "actual admitted auxiliary materialization required")
    _require(_bytes_binding(inputs) == inputs._binding_raw, "materialized input bytes changed")
    audit, _, comparison_raw = _load_audit(inputs.repository)
    try:
        audit.verify_source(inputs.historical_source, "historical")
    except (OSError, subprocess.SubprocessError, ValueError) as error:
        raise ContractError("historical source revalidation failed: " + str(error)) from error
    _require(identity(inputs.historical_dataset_raw) == HISTORICAL_DATASET
             and identity(inputs.historical_manifest_raw) == HISTORICAL_MANIFEST,
             "historical data/manifest commitment mismatch")
    payload = parse_json(inputs.historical_payload_raw, canonical=True)
    _validate_historical(audit, payload, parse_json(comparison_raw, canonical=True))
    _require(json_bytes(payload["dataset"]) == inputs.historical_dataset_raw
             and json_bytes(payload["manifest"]) == inputs.historical_manifest_raw,
             "historical payload/data disagreement")
    receipt = inputs.receipt
    _require(_source_receipt(_source_snapshot()) == receipt["prospective_source"],
             "prospective source changed after materialization")
    _require(_bijection(audit, payload["dataset"], parse_json(inputs.dataset_raw, canonical=True))
             == receipt["mapping"], "materialized row correspondence changed")
